// Builds public/app/js/lucide-subset.js: a small window.lucide replacement
// containing only the icons this app actually uses, instead of shipping the
// full 400KB lucide UMD bundle to every page.
//
// Icon names are discovered by scanning:
//   - data-lucide="..." in public/app HTML and JS
//   - renderIcon('...') literals in public/app JS
//   - icon: '...' / "icon": "..." literals in public/api, lib and public/app JS
//   - every ICON_ALIASES target in public/app/js/icons.js
//
// Re-run after adding a new icon anywhere: node scripts/generate-lucide-subset.js
const fs = require('fs');
const path = require('path');
const lucide = require('lucide');

const ROOT = path.join(__dirname, '..');
const OUTPUT_PATH = path.join(ROOT, 'public', 'app', 'js', 'lucide-subset.js');

const SCAN_DIRS = [
  path.join(ROOT, 'public', 'app'),
  path.join(ROOT, 'public', 'api'),
  path.join(ROOT, 'lib')
];
const SCAN_EXTENSIONS = new Set(['.html', '.js', '.json']);
const SKIP_DIRS = new Set(['node_modules', 'steam', 'android', 'map']);

// Icons referenced dynamically (e.g. rankings-ui.js topRankIcons array) that
// the literal-pattern scan below cannot discover.
const EXTRA_ICONS = ['crown', 'trophy', 'medal'];

function collectFiles(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) collectFiles(path.join(dir, entry.name), out);
    } else if (SCAN_EXTENSIONS.has(path.extname(entry.name))) {
      out.push(path.join(dir, entry.name));
    }
  }
  return out;
}

function collectRequestedNames() {
  const kebabNames = new Set();
  const pascalNames = new Set();
  const patterns = [
    /data-lucide="([a-z0-9-]+)"/g,
    /renderIcon\('([a-z0-9-]+)'/g,
    /icon: '([a-z0-9-]+)'/g,
    /"icon"\s*:\s*"([a-z0-9-]+)"/g
  ];

  for (const file of SCAN_DIRS.flatMap((dir) => collectFiles(dir))) {
    if (path.resolve(file) === path.resolve(OUTPUT_PATH)) continue;
    const content = fs.readFileSync(file, 'utf8');
    for (const pattern of patterns) {
      for (const match of content.matchAll(pattern)) kebabNames.add(match[1]);
    }
  }

  for (const name of EXTRA_ICONS) kebabNames.add(name);

  // Every alias target in icons.js is reachable via renderIcon(aliasName).
  const iconsJs = fs.readFileSync(path.join(ROOT, 'public', 'app', 'js', 'icons.js'), 'utf8');
  const aliasBlock = /const ICON_ALIASES = \{([\s\S]*?)\};/.exec(iconsJs);
  if (!aliasBlock) throw new Error('Could not find ICON_ALIASES in icons.js');
  for (const match of aliasBlock[1].matchAll(/:\s*'([A-Za-z0-9]+)'/g)) pascalNames.add(match[1]);

  return { kebabNames, pascalNames };
}

// Mirrors toPascalCase in icons.js so dynamic renderIcon(kebab) lookups resolve.
function toPascalCase(value) {
  return String(value || '').replace(/(^\w|-\w)/g, (part) => part.replace(/-/, '').toUpperCase());
}

function main() {
  const { kebabNames, pascalNames } = collectRequestedNames();
  const realKeys = new Map(Object.keys(lucide.icons).map((key) => [key.toLowerCase(), key]));
  const resolveKey = (name) => realKeys.get(String(name).replace(/-/g, '').toLowerCase()) || null;

  const icons = {}; // every key form icons.js may look up (Pascal + aliases)
  const kebabIcons = {}; // data-lucide names for createIcons
  const missing = [];

  for (const kebab of kebabNames) {
    const key = resolveKey(kebab);
    if (!key) {
      // Non-lucide names (custom image icons like soul/souls, alias-only names
      // such as potion) resolve through ICON_ALIASES or renderImageIcon instead.
      continue;
    }
    icons[key] = lucide.icons[key];
    icons[toPascalCase(kebab)] = lucide.icons[key];
    kebabIcons[kebab] = lucide.icons[key];
  }

  for (const pascal of pascalNames) {
    const key = resolveKey(pascal);
    if (!key) {
      missing.push(pascal);
      continue;
    }
    icons[key] = lucide.icons[key];
    icons[pascal] = lucide.icons[key];
  }

  if (missing.length) {
    throw new Error(`ICON_ALIASES point at unknown lucide icons: ${missing.join(', ')}`);
  }

  const bundle = `// Generated by scripts/generate-lucide-subset.js — do not edit by hand.
// Minimal stand-in for the lucide UMD bundle with only the icons this app uses.
(function () {
  'use strict';

  const icons = ${JSON.stringify(icons)};
  const kebabIcons = ${JSON.stringify(kebabIcons)};
  const defaultAttributes = {
    xmlns: 'http://www.w3.org/2000/svg',
    width: 24,
    height: 24,
    viewBox: '0 0 24 24',
    fill: 'none',
    stroke: 'currentColor',
    'stroke-width': 2,
    'stroke-linecap': 'round',
    'stroke-linejoin': 'round'
  };

  function createElement(iconNode, attributes = {}) {
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    const merged = { ...defaultAttributes, ...attributes };
    Object.entries(merged).forEach(([name, value]) => {
      if (value !== null && value !== undefined && value !== '') svg.setAttribute(name, String(value));
    });
    (iconNode || []).forEach(([tag, attrs]) => {
      const child = document.createElementNS('http://www.w3.org/2000/svg', tag);
      Object.entries(attrs || {}).forEach(([name, value]) => child.setAttribute(name, String(value)));
      svg.appendChild(child);
    });
    return svg;
  }

  function createIcons(options = {}) {
    const attrs = options.attrs || {};
    document.querySelectorAll('[data-lucide]').forEach((element) => {
      const name = element.getAttribute('data-lucide');
      const iconNode = kebabIcons[name];
      if (!iconNode) {
        console.warn('lucide-subset: unknown icon "' + name + '" — re-run scripts/generate-lucide-subset.js');
        return;
      }

      const classes = ['lucide', 'lucide-' + name];
      if (attrs.class) classes.push(String(attrs.class));
      if (element.getAttribute('class')) classes.push(element.getAttribute('class'));

      const svg = createElement(iconNode, { ...attrs, class: classes.join(' ') });
      for (const attribute of element.attributes) {
        if (attribute.name === 'data-lucide' || attribute.name === 'class') continue;
        svg.setAttribute(attribute.name, attribute.value);
      }
      element.replaceWith(svg);
    });
  }

  window.lucide = { icons, createElement, createIcons };
})();
`;

  fs.writeFileSync(OUTPUT_PATH, bundle);
  const iconCount = Object.keys(kebabIcons).length;
  const sizeKb = Math.round(fs.statSync(OUTPUT_PATH).size / 1024);
  console.log(`lucide-subset.js written: ${iconCount} data-lucide icons, ${Object.keys(icons).length} lookup keys, ${sizeKb}KB`);
}

main();
